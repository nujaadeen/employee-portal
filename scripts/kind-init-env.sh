#!/usr/bin/env bash
# Creates infra/.env for the kind cluster with RANDOM secrets, if the file does not exist yet. Never overwrites, never prints a value.
set -euo pipefail
source "$(dirname "$0")/lib/kind-common.sh"
[ -f "$ENV_FILE" ] && { log "infra/.env exists, left alone"; exit 0; }
need openssl
rnd() { openssl rand -base64 24 | tr -d '/+=\n' | cut -c1-28; }
umask 077
{
  echo "# Generated by scripts/kind-init-env.sh for the local kind cluster. Never commit this file."
  echo "POSTGRES_PASSWORD=$(rnd)"
  echo "KEYCLOAK_ADMIN=admin"
  echo "KEYCLOAK_ADMIN_PASSWORD=$(rnd)"
  echo "PORTAL_SERVICE_CLIENT_SECRET=$(rnd)"
  echo "PORTAL_BACKEND_AI_CLIENT_SECRET=$(rnd)"
  echo "GITEA_OIDC_CLIENT_SECRET=$(rnd)"
  echo "GITEA_WEBHOOK_SECRET=$(rnd)"
  echo "GITEA_ADMIN_PASSWORD=$(rnd)"
  echo "SOCIAL_TOKEN_KEY=$(openssl rand -base64 32)"
  echo "# Social sign-in is optional: leave empty to disable"
  echo "GOOGLE_CLIENT_ID="; echo "GOOGLE_CLIENT_SECRET="; echo "GITHUB_CLIENT_ID="; echo "GITHUB_CLIENT_SECRET="; echo "FACEBOOK_CLIENT_ID="; echo "FACEBOOK_CLIENT_SECRET="
} > "$ENV_FILE"
log "created infra/.env with generated secrets (values not shown)"
