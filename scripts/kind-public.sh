#!/usr/bin/env bash
# Shares the kind cluster with your team through ngrok (one public address), safely.
#   scripts/kind-public.sh up [domain] [--open]   expose it. Domain: NGROK_DOMAIN or the argument (my-name.ngrok-free.dev).
#                                         --open: no basic-auth prompt, anyone with the link can open the sign-in page
#   scripts/kind-public.sh start          start the tunnel only (after a reboot or a new session); nothing else changes
#   scripts/kind-public.sh status         is it up, what is the address
#   scripts/kind-public.sh check          tests through the public address (unauthenticated is refused, admin console is closed, ...)
#   scripts/kind-public.sh stop           stop the tunnel only
#   scripts/kind-public.sh local          stop the tunnel AND return to the local-only set-up (http://portal.baracel.local)
# What "up" changes, and why (see docs/ngrok.md):
#   * ONE address: the portal at /, Keycloak at /auth, the API at /api. The issuer becomes https://<domain>/auth/realms/baracel for everybody.
#   * HTTP basic authentication in front of the web app (user and password in infra/public.env, which is git-ignored and never printed).
#   * The demo users get a NEW shared password (also in infra/public.env), self-registration is switched off and the dev-only direct grant
#     client portal-dev-cli is disabled, because the whole internet can reach the Keycloak login page.
#   * Keycloak's admin console and master realm answer only from this machine. Gitea is not published.
set -euo pipefail
source "$(dirname "$0")/lib/kind-common.sh"
PUB_ENV="$ROOT/infra/public.env"
PID_FILE=/tmp/baracel-ngrok.pid
CHART="$ROOT/infra/helm/baracel-portal"
cmd=${1:-help}; shift || true

pub_value() { [ -f "$PUB_ENV" ] || return 1; grep -E "^${1}=" "$PUB_ENV" | tail -1 | cut -d= -f2-; }
ngrok_running() { [ -f "$PID_FILE" ] && kill -0 "$(cat "$PID_FILE")" 2>/dev/null; }
tunnel_url() { curl -s -m3 http://127.0.0.1:4040/api/tunnels 2>/dev/null | python3 -c 'import sys,json; d=json.load(sys.stdin); print(d["tunnels"][0]["public_url"] if d["tunnels"] else "")' 2>/dev/null || true; }
stop_tunnel() { if ngrok_running; then kill "$(cat "$PID_FILE")" 2>/dev/null || true; rm -f "$PID_FILE"; log "ngrok tunnel stopped"; else log "no tunnel started by this script"; fi; }
argo_managed() { kubectl --context "$KIND_CONTEXT" -n argocd get application baracel-portal >/dev/null 2>&1; }
gateway() { docker network inspect kind -f '{{range .IPAM.Config}}{{.Gateway}} {{end}}' | tr ' ' '\n' | grep -E '^[0-9]+\.[0-9]+\.[0-9]+\.[0-9]+$' | head -1; }

helm_values_args() { # local or public
  local llm; llm=$(kn get configmap portal-config -o jsonpath='{.data.AI_LLM_PROVIDER}')
  printf -- '-f %s -f %s --set ollama.hostAddress=%s --set config.ai.llmProvider=%s' "$CHART/values-kind.yaml" "$CHART/values-public.yaml" "$(gateway)" "$llm"
}

case "$cmd" in
up)
  need ngrok helm kubectl openssl python3 curl docker
  cluster_exists || die "cluster $KIND_CLUSTER does not exist: run scripts/kind-up.sh (KIND_DEPLOY=helm) first"
  kn get deployment portal-backend -o jsonpath='{.metadata.labels.app\.kubernetes\.io/managed-by}' | grep -qx Helm || die "the cluster was not deployed with Helm. Run: KIND_DEPLOY=helm scripts/kind-up.sh (delete the namespace first when it holds a Kustomize deployment)"
  OPEN=0; args=(); for a in "$@"; do if [ "$a" = "--open" ]; then OPEN=1; else args+=("$a"); fi; done
  DOMAIN=${args[0]:-${NGROK_DOMAIN:-$(pub_value NGROK_DOMAIN || true)}}
  [ -n "$DOMAIN" ] || die "no domain. Give it: scripts/kind-public.sh up my-name.ngrok-free.dev  (the dashboard at https://dashboard.ngrok.com/domains lists yours)"
  [[ "$DOMAIN" =~ ^[a-z0-9]([a-z0-9.-]*[a-z0-9])?$ ]] || die "'$DOMAIN' is not a host name"
  ngrok config check >/dev/null 2>&1 || die "ngrok has no valid configuration: run  ngrok config add-authtoken <your token>  once (dashboard.ngrok.com/get-started/your-authtoken)"

  # 1. credentials file (git-ignored, mode 600, never printed)
  if [ ! -f "$PUB_ENV" ]; then
    umask 077
    rnd() { openssl rand -base64 24 | tr -d '/+=\n' | cut -c1-20; }
    { echo "# Generated by scripts/kind-public.sh. Share the BASIC auth and the DEMO password with your team. Never commit this file."
      echo "NGROK_DOMAIN=$DOMAIN"; echo "PUBLIC_BASIC_USER=team"; echo "PUBLIC_BASIC_PASSWORD=$(rnd)"; echo "PUBLIC_DEMO_PASSWORD=$(rnd)"; } > "$PUB_ENV"
    log "created infra/public.env with generated passwords (values not shown)"
  else sed -i "s|^NGROK_DOMAIN=.*|NGROK_DOMAIN=$DOMAIN|" "$PUB_ENV"; fi
  chmod 600 "$PUB_ENV"

  # 2. basic auth Secret for the ingress (not in --open mode)
  sed -i '/^PUBLIC_MODE=/d' "$PUB_ENV"; echo "PUBLIC_MODE=$([ "$OPEN" = 1 ] && echo open || echo basic)" >> "$PUB_ENV"
  if [ "$OPEN" = 0 ]; then
  hash=$(openssl passwd -apr1 "$(pub_value PUBLIC_BASIC_PASSWORD)")
  tmp=$(mktemp); chmod 600 "$tmp"; printf '%s:%s\n' "$(pub_value PUBLIC_BASIC_USER)" "$hash" > "$tmp"
  kn create secret generic portal-basic-auth --from-file=auth="$tmp" --dry-run=client -o yaml | kn apply -f - >/dev/null; rm -f "$tmp"
  fi

  # 3. ingress-nginx trusts the headers ngrok sets (client address and https), so Keycloak builds https links
  cur=$(k -n ingress-nginx get configmap ingress-nginx-controller -o jsonpath='{.data.use-forwarded-headers}' 2>/dev/null || true)
  if [ "$cur" != "true" ]; then
    k -n ingress-nginx patch configmap ingress-nginx-controller --type merge -p '{"data":{"use-forwarded-headers":"true"}}' >/dev/null
    k -n ingress-nginx rollout restart deployment/ingress-nginx-controller >/dev/null
    k -n ingress-nginx rollout status deployment/ingress-nginx-controller --timeout=180s >/dev/null
  fi

  # 4. the chart in public mode
  log "helm upgrade: one public address $DOMAIN (Keycloak under /auth, basic auth, admin console closed)"
  k wait --namespace ingress-nginx --for=condition=ready pod --selector=app.kubernetes.io/component=controller --timeout=180s >/dev/null
  if argo_managed; then
    log "Argo CD manages the release: updating the Application (public values)"
    "$ROOT/scripts/kind-argocd.sh" deploy --mode public >/dev/null
  else
  # the controller's admission webhook may need a few more seconds after a restart: try again before giving up
  for attempt in 1 2 3 4 5; do
    # shellcheck disable=SC2046
    if helm --kube-context "$KIND_CONTEXT" upgrade baracel-portal "$CHART" -n "$NS" $(helm_values_args) --set "global.hosts.portal=$DOMAIN" --set "global.hosts.auth=$DOMAIN" ${OPEN:+$([ "$OPEN" = 1 ] && echo '--set ingress.basicAuth.secretName=')} >/dev/null 2>&1; then break; fi
    [ "$attempt" = 5 ] && die "helm upgrade failed five times (helm -n $NS --kube-context $KIND_CONTEXT status baracel-portal)"; sleep 10
  done
  fi
  for d in keycloak portal-backend portal-frontend ai-service; do kn rollout status "deployment/$d" --timeout=900s >/dev/null; done

  # 5. Keycloak realm: redirect URIs, shared demo password, no self-registration, no dev direct grants
  log "Keycloak: redirect URIs, demo password, registration off, portal-dev-cli off"
  pub_value PUBLIC_DEMO_PASSWORD | kn exec -i deploy/keycloak -- env "D=$DOMAIN" bash -c '
    read -r PW
    KC=/opt/keycloak/bin/kcadm.sh
    $KC config credentials --server "http://localhost:8080${KC_HTTP_RELATIVE_PATH:-}" --realm master --user "$KC_BOOTSTRAP_ADMIN_USERNAME" --password "$KC_BOOTSTRAP_ADMIN_PASSWORD" >/dev/null
    ID=$($KC get clients -r baracel -q clientId=portal-web --fields id --format csv --noquotes)
    $KC update clients/$ID -r baracel -s "redirectUris=[\"http://portal.baracel.local/*\",\"https://$D/*\"]" -s "webOrigins=[\"http://portal.baracel.local\",\"https://$D\"]" -s "attributes.\"post.logout.redirect.uris\"=http://portal.baracel.local/*##https://$D/*" >/dev/null
    $KC update realms/baracel -s registrationAllowed=false >/dev/null
    CLI=$($KC get clients -r baracel -q clientId=portal-dev-cli --fields id --format csv --noquotes)
    $KC update clients/$CLI -r baracel -s directAccessGrantsEnabled=false >/dev/null
    for u in $($KC get users -r baracel --fields username --format csv --noquotes); do
      case "$u" in service-account-*) continue;; esac
      $KC set-password -r baracel --username "$u" --new-password "$PW" >/dev/null
    done'

  # 6. ngrok
  if ngrok_running; then stop_tunnel; fi
  log "starting ngrok -> http://127.0.0.1:80 (the kind ingress)"
  setsid nohup ngrok http --url="https://$DOMAIN" 80 --log=stdout --log-format=json > /tmp/baracel-ngrok.log 2>&1 &
  echo $! > "$PID_FILE"
  for _ in $(seq 1 30); do [ -n "$(tunnel_url)" ] && break; sleep 1; done
  [ -n "$(tunnel_url)" ] || { tail -5 /tmp/baracel-ngrok.log | cut -c1-200; die "ngrok did not start (domain not yours, or already used by another tunnel?)"; }
  cat <<EOF

The portal is public: https://$DOMAIN/
  Share with the team:  the address above$([ "$OPEN" = 1 ] && echo " (open: no basic-auth prompt)" || echo ", and from infra/public.env: PUBLIC_BASIC_USER / PUBLIC_BASIC_PASSWORD (browser prompt)")
                        and a demo user with PUBLIC_DEMO_PASSWORD (infra/public.env): aisha.rahman (Sales), omar.haddad (Manager), lena.fischer (HR),
                        priya.nair (Engineer), daniel.okoye (Admin), sara.qureshi (Employee)
  It works while this laptop, the kind cluster and the tunnel are up. Stop sharing: scripts/kind-public.sh stop   (or: local)
  ngrok shows a warning page on the first visit of each browser: choose "Visit Site".
EOF
  ;;
start)
  need ngrok curl
  D=$(pub_value NGROK_DOMAIN || true); [ -n "$D" ] || die "no infra/public.env: run up first"
  if ngrok_running; then log "tunnel already running: $(tunnel_url)"; exit 0; fi
  setsid nohup ngrok http --url="https://$D" 80 --log=stdout --log-format=json > /tmp/baracel-ngrok.log 2>&1 < /dev/null &
  echo $! > "$PID_FILE"
  for _ in $(seq 1 30); do [ -n "$(tunnel_url)" ] && break; sleep 1; done
  [ -n "$(tunnel_url)" ] || die "ngrok did not start (see /tmp/baracel-ngrok.log)"
  log "tunnel up: $(tunnel_url)"
  ;;
status)
  if ngrok_running; then echo "tunnel up: $(tunnel_url)"; else echo "no tunnel started by this script"; fi
  [ -f "$PUB_ENV" ] && echo "domain in infra/public.env: $(pub_value NGROK_DOMAIN)"
  ;;
check)
  need curl python3
  D=$(pub_value NGROK_DOMAIN || true); [ -n "$D" ] || die "no infra/public.env: run up first"
  U=$(pub_value PUBLIC_BASIC_USER); P=$(pub_value PUBLIC_BASIC_PASSWORD)
  fails=0; t() { if [ "$2" = "$3" ]; then printf 'PASS  %s\n' "$1"; else printf 'FAIL  %s (got %s, expected %s)\n' "$1" "$2" "$3"; fails=$((fails+1)); fi; }
  c() { curl -s -o /dev/null -w '%{http_code}' -m 30 "$@"; }
  if [ "$(pub_value PUBLIC_MODE || echo basic)" = open ]; then
    t "open mode: the web app opens without a password" "$(c https://$D/)" 200
  else
    t "the web app asks for the basic-auth password (401 without it)" "$(c https://$D/)" 401
    t "the web app opens with the basic-auth password" "$(c -u "$U:$P" https://$D/)" 200
    t "wrong basic-auth password is refused" "$(c -u "$U:wrong" https://$D/)" 401
  fi
  iss=$(curl -s -m 30 "https://$D/auth/realms/baracel/.well-known/openid-configuration" | python3 -c 'import sys,json; print(json.load(sys.stdin)["issuer"])' 2>/dev/null)
  t "Keycloak discovery is public with issuer https://$D/auth/realms/baracel" "$iss" "https://$D/auth/realms/baracel"
  t "Keycloak admin console is closed from outside (403)" "$(c https://$D/auth/admin/master/console/)" 403
  t "Keycloak master realm is closed from outside (403)" "$(c https://$D/auth/realms/master/.well-known/openid-configuration)" 403
  t "the API refuses a call without a token (401)" "$(c https://$D/api/me)" 401
  t "Gitea has no public Ingress" "$(kn get ingress gitea >/dev/null 2>&1 && echo present || echo absent)" absent
  t "self-registration is off (no register page)" "$(c "https://$D/auth/realms/baracel/protocol/openid-connect/registrations?client_id=portal-web&response_type=code&redirect_uri=https://$D/callback&scope=openid")" 400
  [ "$fails" -eq 0 ]
  ;;
stop) stop_tunnel ;;
local)
  need helm kubectl
  stop_tunnel
  log "back to the local-only set-up"
  if argo_managed; then "$ROOT/scripts/kind-argocd.sh" deploy --mode local >/dev/null
  else helm --kube-context "$KIND_CONTEXT" upgrade baracel-portal "$CHART" -n "$NS" -f "$CHART/values-kind.yaml" --set "ollama.hostAddress=$(gateway)" \
    --set "config.ai.llmProvider=$(kn get configmap portal-config -o jsonpath='{.data.AI_LLM_PROVIDER}')" >/dev/null; fi
  for d in keycloak portal-backend portal-frontend ai-service; do kn rollout status "deployment/$d" --timeout=900s >/dev/null; done
  kn exec -i deploy/keycloak -- bash -c '
    KC=/opt/keycloak/bin/kcadm.sh
    $KC config credentials --server http://localhost:8080 --realm master --user "$KC_BOOTSTRAP_ADMIN_USERNAME" --password "$KC_BOOTSTRAP_ADMIN_PASSWORD" >/dev/null
    $KC update realms/baracel -s registrationAllowed=true >/dev/null
    CLI=$($KC get clients -r baracel -q clientId=portal-dev-cli --fields id --format csv --noquotes)
    $KC update clients/$CLI -r baracel -s directAccessGrantsEnabled=true >/dev/null
    for u in $($KC get users -r baracel --fields username --format csv --noquotes); do
      case "$u" in service-account-*) continue;; esac
      $KC set-password -r baracel --username "$u" --new-password "ChangeMe123!" >/dev/null
    done'
  k -n ingress-nginx patch configmap ingress-nginx-controller --type merge -p '{"data":{"use-forwarded-headers":"false"}}' >/dev/null
  log "local again: http://portal.baracel.local (demo password ChangeMe123!, registration on, portal-dev-cli on)"
  ;;
*) sed -n '2,/^set -euo/p' "$0" | sed '$d' | sed 's/^# \{0,1\}//'; exit 1 ;;
esac
